#!/usr/bin/env node
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { fileURLToPath } from 'node:url'
import { readExtensionManifests } from './extension-shared.mjs'

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)))
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
const manifests = readExtensionManifests(path.join(root, 'app/extensions'))

const definitions = [
  {
    id: 'apps',
    table: 'ext_apps_catalog',
    fields: [
      'name', 'types', 'slug', 'image_url', 'subtitle', 'price_amount', 'content', 'downs', 'status',
      'unique_name', 'package_url', 'version', 'installs_json', 'settings_json',
      'seo_title', 'seo_keywords', 'seo_description', 'created_at', 'updated_at',
    ],
    sourceFields: ['name', 'types', 'slug', 'attach_id', 'subtitle', 'sales_price', 'content', 'downs', 'status', 'unique_name', 'package_url', 'version', 'installs', 'setting'],
  },
  {
    id: 'theme',
    table: 'ext_theme_catalog',
    fields: [
      'name', 'category', 'slug', 'image_url', 'subtitle', 'price_amount', 'content', 'downs', 'status',
      'unique_name', 'package_url', 'demo_url', 'settings_json',
      'seo_title', 'seo_keywords', 'seo_description', 'created_at', 'updated_at',
    ],
    sourceFields: ['name', 'category_id', 'slug', 'attach_id', 'subtitle', 'sales_price', 'content', 'downs', 'status', 'unique_name', 'package_url', 'demo_url', 'setting'],
  },
]

for (const definition of definitions) {
  const manifest = manifests.find(item => item.id === definition.id)
  assert.ok(manifest, `${definition.id} extension manifest is missing`)
  assert.deepEqual(manifest.capabilities.map(item => item.key), ['catalog'], `${definition.id} must expose only the catalog capability`)
  assert.equal(manifest.capabilities[0].editable, true, `${definition.id} catalog capability must support view/edit tiers`)
  assert.equal(manifest.adminPages.length, 1, `${definition.id} must provide one catalog admin page`)
  assert.equal(manifest.adminPages[0].capability, 'catalog', `${definition.id} admin page must use the catalog capability`)

  const expectedRoutes = new Set([
    'GET:catalog/list', 'GET:catalog/detail', 'POST:catalog/create', 'PATCH:catalog/update', 'DELETE:catalog/delete',
  ])
  assert.deepEqual(
    new Set(manifest.adminApis.map(api => `${api.method.toUpperCase()}:${api.path}`)),
    expectedRoutes,
    `${definition.id} CRUD routes are incomplete`,
  )
  assert.ok(manifest.adminApis.every(api => api.capability === 'catalog'), `${definition.id} APIs must all require catalog capability`)

  const serverSource = read(`app/extensions/${definition.id}/server/catalog.ts`)
  const pageSource = read(`app/extensions/${definition.id}/admin/pages/catalog.vue`)
  for (const marker of [
    "statusCode: 409", 'status === STATUS_PUBLISHED', 'status = ${STATUS_DRAFT}',
    'sql.identifier(TABLE)', 'readBody(event)', 'readUrl(', 'readInteger(', 'assertUnique(',
  ]) {
    assert.ok(serverSource.includes(marker), `${definition.id} server guard is missing ${marker}`)
  }
  assert.ok(!serverSource.includes('sql.raw('), `${definition.id} must not construct catalog queries with sql.raw`)
  assert.ok(serverSource.includes('globalThis.crypto.randomUUID()'), `${definition.id} IDs must be generated by the application`)
  for (const marker of ['usePagination(15)', 'v-model:open="modalOpen"', '<template #content>', 'toggleStatus(', 'removeItem(', 'applyFilters']) {
    assert.ok(pageSource.includes(marker), `${definition.id} management page is missing ${marker}`)
  }

  assert.equal(manifest.database.migrations.length, 1, `${definition.id} must provide its initial migration`)
  const migration = manifest.database.migrations[0]
  for (const dialect of ['sqlite', 'postgresql', 'mysql']) {
    const dialectSource = migration.dialects[dialect].statements.join('\n')
    assert.ok(dialectSource.includes(definition.table), `${definition.id} ${dialect} migration uses the wrong table`)
    for (const field of definition.fields) {
      assert.ok(dialectSource.includes(field), `${definition.id} ${dialect} migration is missing ${field}`)
    }
    assert.ok(dialectSource.includes('CHECK'), `${definition.id} ${dialect} migration must constrain status and counters`)
  }
}

const sourceRoots = {
  apps: '/Users/hugh/code/kuaiqin/shoply/plugins/app/Apps',
  theme: '/Users/hugh/code/kuaiqin/shoply/plugins/app/Theme',
}
for (const definition of definitions) {
  const sourceRoot = sourceRoots[definition.id]
  if (!fs.existsSync(sourceRoot)) continue
  const source = fs.readdirSync(sourceRoot, { recursive: true, withFileTypes: true })
    .filter(entry => entry.isFile() && /\.(php|html?|ft)$/i.test(entry.name))
    .map(entry => fs.readFileSync(path.join(entry.parentPath, entry.name), 'utf8'))
    .join('\n')
  for (const field of definition.sourceFields) {
    assert.ok(source.includes(field), `${definition.id} legacy source no longer contains expected field ${field}`)
  }
}

const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), 'apay-shoply-management-'))
try {
  const database = new DatabaseSync(path.join(temporaryDirectory, 'catalog.db'))
  try {
    for (const definition of definitions) {
      const manifest = manifests.find(item => item.id === definition.id)
      for (const statement of manifest.database.migrations[0].dialects.sqlite.statements) database.exec(statement)
    }

    const now = new Date().toISOString()
    database.prepare(`
      INSERT INTO ext_apps_catalog (
        id, name, types, slug, image_url, subtitle, price_amount, content, downs, status,
        unique_name, package_url, version, installs_json, settings_json,
        seo_title, seo_keywords, seo_description, created_at, updated_at
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `).run(
      '00000000-0000-4000-8000-000000000001', 'Example App', 'plugin', 'example-app', null, '', 9900, '', 0, 10,
      'vendor/example-app', 'https://example.com/app.zip', '1.0.0', '[]', '{}', '', '', '', now, now,
    )
    assert.throws(() => database.prepare(`
      INSERT INTO ext_apps_catalog (
        id, name, types, slug, unique_name, package_url, version, created_at, updated_at
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    `).run(
      '00000000-0000-4000-8000-000000000002', 'Duplicate App', 'plugin', 'example-app',
      'vendor/duplicate-app', 'https://example.com/duplicate.zip', '1.0.0', now, now,
    ), /unique/i, 'apps slug uniqueness must be enforced')
    database.prepare('UPDATE ext_apps_catalog SET status = 20, updated_at = ? WHERE slug = ?').run(now, 'example-app')
    const publishedAppDelete = database.prepare('DELETE FROM ext_apps_catalog WHERE slug = ? AND status = 10').run('example-app')
    assert.equal(publishedAppDelete.changes, 0, 'published apps must not match the safe delete statement')
    database.prepare('UPDATE ext_apps_catalog SET status = 10 WHERE slug = ?').run('example-app')
    assert.equal(database.prepare('DELETE FROM ext_apps_catalog WHERE slug = ? AND status = 10').run('example-app').changes, 1)

    database.prepare(`
      INSERT INTO ext_theme_catalog (
        id, name, category, slug, image_url, subtitle, price_amount, content, downs, status,
        unique_name, package_url, demo_url, settings_json, seo_title, seo_keywords, seo_description, created_at, updated_at
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `).run(
      '00000000-0000-4000-8000-000000000003', 'Example Theme', 'fashion', 'example-theme', null, '', 12900, '', 0, 20,
      'vendor/example-theme', 'https://example.com/theme.zip', 'https://example.com/demo', '{}', '', '', '', now, now,
    )
    const publishedThemeDelete = database.prepare('DELETE FROM ext_theme_catalog WHERE slug = ? AND status = 10').run('example-theme')
    assert.equal(publishedThemeDelete.changes, 0, 'published themes must not match the safe delete statement')
    database.prepare('UPDATE ext_theme_catalog SET status = 10 WHERE slug = ?').run('example-theme')
    assert.equal(database.prepare('DELETE FROM ext_theme_catalog WHERE slug = ? AND status = 10').run('example-theme').changes, 1)
  } finally {
    database.close()
  }
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true })
}

const registry = read('server/utils/extensionRegistry.generated.ts')
for (const definition of definitions) {
  assert.ok(registry.includes(`"extension": "${definition.id}"`), `${definition.id} is missing from the generated registry`)
  assert.ok(registry.includes(definition.table), `${definition.id} migration is missing from the generated registry`)
}

console.log('✓ Shoply Apps and Theme management extension guard passed')
