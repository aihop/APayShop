#!/usr/bin/env node
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { resolveAvailableThemes, resolveDevThemeEnv, resolveManifestFile, resolveSelectedThemes } from './theme-shared.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(__dirname, '..')
const themesDir = path.join(projectRoot, 'app/themes')
const outputDir = path.join(projectRoot, 'app/generated')
const outputFile = path.join(outputDir, 'theme-build.ts')

const args = process.argv.slice(2)
const forceAllThemes = args.includes('--all')

const getArgValue = (name) => {
  const exact = `--${name}`
  const inline = `--${name}=`

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index]
    if (arg === exact) {
      return args[index + 1] || ''
    }
    if (arg.startsWith(inline)) {
      return arg.slice(inline.length)
    }
  }

  return ''
}

const availableThemes = resolveAvailableThemes(themesDir)
const manifestFile = resolveManifestFile(projectRoot, getArgValue('manifest') || process.env.APAY_THEME_MANIFEST || '')

const selectedThemes = forceAllThemes
  ? availableThemes
  : resolveSelectedThemes({
      themesDir,
      manifestFile,
      explicitThemes: getArgValue('themes'),
      envThemes: resolveDevThemeEnv() || process.env.APAY_BUILD_THEMES || process.env.BUILD_THEMES || '',
    })

const buildGlobObject = (patterns, options) => {
  if (!patterns.length) {
    return '{}'
  }

  const optionLines = Object.entries(options).map(([key, value]) => {
    if (typeof value === 'string') {
      return `    ${key}: '${value}',`
    }
    return `    ${key}: ${value},`
  })

  const entries = patterns
    .map((pattern) => [
      `  ...import.meta.glob('${pattern}', {`,
      ...optionLines,
      '  }),',
    ].join('\n'))
    .join('\n')

  return `{\n${entries}\n}`
}

const pagePatterns = selectedThemes.map((theme) => `../themes/${theme}/pages/**/*.vue`)
const adminManifestPatterns = selectedThemes.map((theme) => `../themes/${theme}/theme.admin.json`)
const adminPagePatterns = selectedThemes.map((theme) => `../themes/${theme}/admin/pages/**/*.vue`)
const adminLocaleEnPatterns = selectedThemes.map((theme) => `../themes/${theme}/locales/admin/en.ts`)
const adminLocaleZhPatterns = selectedThemes.map((theme) => `../themes/${theme}/locales/admin/zh.ts`)

const layoutLoaderObject = selectedThemes.length
  ? `{\n${selectedThemes.map((theme) => `  '${theme}': () => import('../themes/${theme}/layouts/default.vue'),`).join('\n')}\n}`
  : '{}'

const content = `// Auto-generated by scripts/generate-theme-build.mjs
// Do not edit manually.
// Core pages/layout are always available as the default base layer.

export const publishedOptionalThemes = ${JSON.stringify(selectedThemes)} as const
export const publishedOptionalThemeSet = new Set<string>(publishedOptionalThemes as readonly string[])

export const corePageModules = import.meta.glob('../core/pages/**/*.vue', {
  eager: true,
}) as Record<string, { default: unknown }>

export const themePageModules = ${buildGlobObject(pagePatterns, { eager: true })} as Record<
  string,
  { default: unknown }
>

export const themeAdminManifestModules = ${buildGlobObject(adminManifestPatterns, {
  eager: true,
  import: 'default',
})} as Record<string, Record<string, unknown>>

export const themeAdminPageModules = ${buildGlobObject(adminPagePatterns, {
  eager: true,
  import: 'default',
})} as Record<string, unknown>

export const themeAdminLocaleEnModules = ${buildGlobObject(adminLocaleEnPatterns, {
  eager: true,
  import: 'default',
})} as Record<string, Record<string, unknown>>

export const themeAdminLocaleZhModules = ${buildGlobObject(adminLocaleZhPatterns, {
  eager: true,
  import: 'default',
})} as Record<string, Record<string, unknown>>

export const themeLayoutLoaders = ${layoutLoaderObject} as Record<
  string,
  () => Promise<{ default: unknown }>
>
`

fs.mkdirSync(outputDir, { recursive: true })
fs.writeFileSync(outputFile, content)

console.log(
  `[theme-build] generated ${path.relative(projectRoot, outputFile)} for themes: ${selectedThemes.join(',') || 'core-only'}`
)
