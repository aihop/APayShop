#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { readExtensionManifests } from './extension-shared.mjs'

const projectRoot = path.resolve(fileURLToPath(new URL('..', import.meta.url)))
const extensionsDir = path.join(projectRoot, 'app/extensions')
const outputFile = path.join(projectRoot, 'server/utils/extensionRegistry.generated.ts')
const clientOutputFile = path.join(extensionsDir, 'extensionDatabase.generated.ts')
const manifests = readExtensionManifests(extensionsDir)
const imports = []
const adminRoutes = []
const userRoutes = []
const databaseMigrations = []
let handlerIndex = 0

const addRoutes = (manifest, kind, routes, target) => {
  for (const route of routes) {
    const variable = `handler${handlerIndex++}`
    const absoluteHandler = path.join(manifest.root, 'api', kind, route.handler)
    const relativeHandler = path.relative(path.dirname(outputFile), absoluteHandler)
      .split(path.sep).join('/')
      .replace(/\.ts$/, '')
    imports.push(`import ${variable} from '${relativeHandler.startsWith('.') ? relativeHandler : `./${relativeHandler}`}'`)
    target.push({
      extension: manifest.id,
      method: route.method.toUpperCase(),
      path: route.path,
      ...(route.capability ? { capability: route.capability } : {}),
      variable,
    })
  }
}

for (const manifest of manifests) {
  addRoutes(manifest, 'admin', manifest.adminApis, adminRoutes)
  addRoutes(manifest, 'user', manifest.userApis, userRoutes)
  for (const migration of manifest.database.migrations) {
    databaseMigrations.push({
      extension: manifest.id,
      id: migration.id,
      dialects: migration.dialects,
    })
  }
}

const serializeRoutes = routes => routes.map(route => `  { extension: ${JSON.stringify(route.extension)}, method: ${JSON.stringify(route.method)}, path: ${JSON.stringify(route.path)},${route.capability ? ` capability: ${JSON.stringify(route.capability)},` : ''} handler: ${route.variable} },`).join('\n')
const publicManifests = manifests.map(({ root, manifestPath, adminApis, userApis, database, ...manifest }) => ({
  ...manifest,
  adminApis: adminApis.map(({ handler, ...api }) => api),
  userApis: userApis.map(({ handler, ...api }) => api),
  database: {
    migrations: database.migrations.map(migration => ({
      id: migration.id,
      checksums: Object.fromEntries(Object.entries(migration.dialects).map(([dialect, value]) => [dialect, value.checksum])),
    })),
  },
}))

const content = `// Auto-generated by scripts/generate-extension-build.mjs. Do not edit manually.
import type { EventHandler } from 'h3'
${imports.join('\n')}

export const extensionManifests = ${JSON.stringify(publicManifests, null, 2)} as const

export interface ExtensionApiRoute {
  extension: string
  method: string
  path: string
  capability?: string
  handler: EventHandler
}

export const extensionAdminApiRoutes: ExtensionApiRoute[] = [
${serializeRoutes(adminRoutes)}
]

export const extensionUserApiRoutes: ExtensionApiRoute[] = [
${serializeRoutes(userRoutes)}
]

export type ExtensionDatabaseDialect = 'sqlite' | 'postgresql' | 'mysql'

export interface ExtensionDatabaseMigration {
  extension: string
  id: string
  dialects: Record<ExtensionDatabaseDialect, { file: string, checksum: string, statements: string[] }>
}

export const extensionDatabaseMigrations: ExtensionDatabaseMigration[] = ${JSON.stringify(databaseMigrations, null, 2)}
`

fs.mkdirSync(path.dirname(outputFile), { recursive: true })
fs.writeFileSync(outputFile, content)
const clientRequirements = Object.fromEntries(manifests.map(manifest => [
  manifest.id,
  Object.fromEntries(['sqlite', 'postgresql', 'mysql'].map(dialect => [
    dialect,
    Object.fromEntries(manifest.database.migrations.map(migration => [migration.id, migration.dialects[dialect].checksum])),
  ])),
]))
fs.writeFileSync(clientOutputFile, `// Auto-generated by scripts/generate-extension-build.mjs. Do not edit manually.\nexport const extensionDatabaseRequirements: Record<string, Record<'sqlite' | 'postgresql' | 'mysql', Record<string, string>>> = ${JSON.stringify(clientRequirements, null, 2)}\n`)
console.log(`[extensions] generated registries for ${manifests.length} extension(s)`)
